/// Canonical error code from the module 12 error dictionary.
#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ErrorCode {
    /// Invalid QingYin credential.
    AuthInvalid,
    /// The principal does not have the required permission.
    PermissionDenied,
    /// Tenant or provider quota was exhausted.
    QuotaExhausted,
    /// A request rate limit was exceeded.
    RateLimited,
    /// The requested task, codec, language, or profile is unsupported.
    UnsupportedCapability,
    /// The request schema or value is invalid.
    InvalidRequest,
    /// Audio encoding, order, or rate is invalid.
    InvalidAudio,
    /// A hard policy denied the request.
    PolicyDenied,
    /// A ticket or lease expired.
    SessionExpired,
    /// The provider is unavailable before a safe boundary.
    ProviderUnavailable,
    /// The provider exceeded its operation deadline.
    ProviderTimeout,
    /// The provider emitted invalid protocol data.
    ProviderProtocolError,
    /// Gateway or provider capacity is exhausted.
    CapacityExceeded,
    /// The session was cancelled.
    Cancelled,
    /// An unexpected internal error occurred.
    InternalError,
}

impl ErrorCode {
    /// Returns the only valid category for this code.
    #[must_use]
    pub const fn category(self) -> ErrorCategory {
        match self {
            Self::AuthInvalid | Self::PermissionDenied => ErrorCategory::Auth,
            Self::QuotaExhausted | Self::RateLimited => ErrorCategory::Quota,
            Self::UnsupportedCapability | Self::InvalidRequest | Self::InvalidAudio => {
                ErrorCategory::Validation
            }
            Self::PolicyDenied => ErrorCategory::Policy,
            Self::SessionExpired | Self::Cancelled => ErrorCategory::Session,
            Self::ProviderUnavailable | Self::ProviderTimeout | Self::ProviderProtocolError => {
                ErrorCategory::Upstream
            }
            Self::CapacityExceeded => ErrorCategory::Capacity,
            Self::InternalError => ErrorCategory::Internal,
        }
    }

    /// Returns whether a retry is safe before stage-specific context is available.
    #[must_use]
    pub const fn default_retryable(self) -> bool {
        matches!(
            self,
            Self::QuotaExhausted
                | Self::RateLimited
                | Self::ProviderUnavailable
                | Self::CapacityExceeded
                | Self::InternalError
        )
    }
}

/// Transport-neutral canonical error before an API request ID is attached.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct CanonicalError {
    /// Stable canonical code.
    pub code: ErrorCode,
    /// Sanitized developer-facing message.
    pub message: String,
    /// Whether retry is safe for this occurrence.
    pub retryable: bool,
    /// Optional retry hint in milliseconds.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub retry_after_ms: Option<u64>,
    /// Optional bounded scope such as a tenant, provider, or gateway gate.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub scope: Option<String>,
    /// Optional reference to access-controlled diagnostic detail.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub diagnostic_id: Option<DiagnosticId>,
}

impl CanonicalError {
    /// Builds an error with canonical default retry behavior.
    #[must_use]
    pub fn new(code: ErrorCode, message: impl Into<String>) -> Self {
        Self {
            code,
            message: message.into(),
            retryable: code.default_retryable(),
            retry_after_ms: None,
            scope: None,
            diagnostic_id: None,
        }
    }

    /// Returns the category derived from the canonical code.
    #[must_use]
    pub const fn category(&self) -> ErrorCategory {
        self.code.category()
    }
}

