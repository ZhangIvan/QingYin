/// Canonical audio format negotiated at the public contract boundary.
#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct AudioSpec {
    /// Audio codec.
    pub codec: AudioCodec,
    /// Optional stream or file container.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub container: Option<AudioContainer>,
    /// Sample rate in hertz.
    pub sample_rate_hz: u32,
    /// Channel count.
    pub channels: u8,
    /// Optional frame duration in milliseconds.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub frame_ms: Option<u16>,
}

impl AudioSpec {
    /// Validates numeric bounds that cannot be represented by the v1 enums.
    #[must_use]
    pub fn is_valid_for_v1(&self) -> bool {
        matches!(self.sample_rate_hz, 8_000 | 16_000 | 24_000 | 48_000)
            && matches!(self.channels, 1 | 2)
            && self
                .frame_ms
                .is_none_or(|frame_ms| (10..=200).contains(&frame_ms))
    }
}

/// Internal session state used to enforce the canonical lifecycle.
#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum SessionState {
    /// Request identity exists but authorization has not completed.
    Created,
    /// Principal and resource ownership were validated.
    Authorized,
    /// Side-effect-free route filtering and scoring is in progress.
    Routing,
    /// Capacity is reserved and the lease is durable.
    Leased,
    /// The selected data-plane channel is being established.
    Connecting,
    /// The session can accept or emit media.
    Active,
    /// New input is closed while accepted work finishes.
    Draining,
    /// A recoverable boundary is being re-established.
    Retrying,
    /// The session completed normally.
    Completed,
    /// The client or service cancelled the session.
    Cancelled,
    /// The lease or session lifetime elapsed.
    Expired,
    /// The session ended with a canonical error.
    Failed,
}

impl SessionState {
    /// Returns whether no later state may replace this state.
    #[must_use]
    pub const fn is_terminal(self) -> bool {
        matches!(
            self,
            Self::Completed | Self::Cancelled | Self::Expired | Self::Failed
        )
    }

    /// Checks one forward transition from the frozen module 01 state machine.
    #[must_use]
    pub const fn can_transition_to(self, next: Self) -> bool {
        if self.is_terminal() {
            return false;
        }

        if matches!(next, Self::Cancelled | Self::Expired | Self::Failed) {
            return true;
        }

        matches!(
            (self, next),
            (Self::Created, Self::Authorized)
                | (Self::Authorized, Self::Routing)
                | (Self::Routing, Self::Leased)
                | (Self::Leased, Self::Connecting)
                | (Self::Connecting, Self::Active)
                | (Self::Active, Self::Draining | Self::Retrying)
                | (Self::Retrying, Self::Active)
                | (Self::Draining, Self::Completed)
        )
    }
}

