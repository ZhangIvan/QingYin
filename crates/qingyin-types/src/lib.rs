const RESOURCE_ID_MIN_LENGTH: usize = 8;
const RESOURCE_ID_MAX_LENGTH: usize = 128;

/// Validated opaque identifier shared by public resource ID wrappers.
#[derive(Clone, Debug, Eq, Hash, PartialEq, Serialize)]
#[serde(transparent)]
pub struct ResourceId(String);

impl ResourceId {
    /// Creates an ID when it satisfies the frozen OpenAPI length bounds.
    #[must_use]
    pub fn new(value: impl Into<String>) -> Option<Self> {
        let value = value.into();
        (RESOURCE_ID_MIN_LENGTH..=RESOURCE_ID_MAX_LENGTH)
            .contains(&value.len())
            .then_some(Self(value))
    }

    /// Returns the identifier as a string slice.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl<'de> Deserialize<'de> for ResourceId {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: Deserializer<'de>,
    {
        let value = String::deserialize(deserializer)?;
        Self::new(value).ok_or_else(|| D::Error::custom("resource ID length must be 8..=128"))
    }
}

impl fmt::Display for ResourceId {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.as_str())
    }
}

macro_rules! typed_resource_id {
    ($(#[$metadata:meta])* $name:ident) => {
        $(#[$metadata])*
        #[derive(Clone, Debug, Deserialize, Eq, Hash, PartialEq, Serialize)]
        #[serde(transparent)]
        pub struct $name(ResourceId);

        impl $name {
            /// Creates a typed ID after applying the public resource ID constraints.
            #[must_use]
            pub fn new(value: impl Into<String>) -> Option<Self> {
                ResourceId::new(value).map(Self)
            }

            /// Returns the identifier as a string slice.
            #[must_use]
            pub fn as_str(&self) -> &str {
                self.0.as_str()
            }

            /// Returns the validated resource ID without discarding its semantic type.
            #[must_use]
            pub fn as_resource_id(&self) -> &ResourceId {
                &self.0
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
                formatter.write_str(self.as_str())
            }
        }
    };
}

