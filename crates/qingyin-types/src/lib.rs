/// Canonical event envelope shared by WebSocket messages and fixture assertions.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct EventEnvelope<T> {
    /// Stable event type.
    #[serde(rename = "type")]
    pub event_type: EventType,
    /// Globally unique event identifier.
    pub event_id: EventId,
    /// Associated QingYin session identifier.
    pub session_id: SessionId,
    /// Strictly increasing sequence inside the session stream.
    pub sequence: EventSequence,
    /// Service-generated event timestamp.
    pub occurred_at_ms: TimestampMs,
    /// Cross-service trace identifier.
    pub trace_id: TraceId,
    /// Type-specific event payload.
    pub data: T,
    /// Event schema version.
    pub schema_version: String,
}

#[cfg(test)]
mod tests {
    use super::{
        AudioCodec, CanonicalError, ErrorCategory, ErrorCode, EventType, ResourceId, SessionId,
        SessionState, TaskKind,
    };

    #[test]
    fn resource_ids_enforce_contract_length_and_semantic_types() {
        assert!(ResourceId::new("ses_abc1").is_some());
        assert!(SessionId::new("ses_abc1").is_some());
        assert!(ResourceId::new("short").is_none());
        assert!(ResourceId::new("x".repeat(129)).is_none());
        assert!(serde_json::from_str::<SessionId>("\"short\"").is_err());
    }

    #[test]
    fn session_state_machine_allows_only_forward_or_terminal_transitions() {
        assert!(SessionState::Created.can_transition_to(SessionState::Authorized));
        assert!(SessionState::Active.can_transition_to(SessionState::Retrying));
        assert!(SessionState::Retrying.can_transition_to(SessionState::Active));
        assert!(SessionState::Draining.can_transition_to(SessionState::Completed));
        assert!(SessionState::Connecting.can_transition_to(SessionState::Failed));

        assert!(!SessionState::Created.can_transition_to(SessionState::Leased));
        assert!(!SessionState::Active.can_transition_to(SessionState::Completed));
        assert!(!SessionState::Completed.can_transition_to(SessionState::Active));
        assert!(!SessionState::Cancelled.can_transition_to(SessionState::Failed));
    }

    #[test]
    fn canonical_error_derives_category_and_retryability() {
        let unavailable =
            CanonicalError::new(ErrorCode::ProviderUnavailable, "provider unavailable");
        assert_eq!(unavailable.category(), ErrorCategory::Upstream);
        assert!(unavailable.retryable);

        let denied = CanonicalError::new(ErrorCode::PermissionDenied, "permission denied");
        assert_eq!(denied.category(), ErrorCategory::Auth);
        assert!(!denied.retryable);
    }

    #[test]
    fn canonical_wire_names_match_frozen_contracts() {
        assert!(matches!(
            serde_json::to_value(TaskKind::Realtime),
            Ok(value) if value == serde_json::json!("realtime")
        ));
        assert!(matches!(
            serde_json::to_value(AudioCodec::PcmS16Le),
            Ok(value) if value == serde_json::json!("pcm_s16le")
        ));
        assert!(matches!(
            serde_json::to_value(EventType::AsrFinalUpdate),
            Ok(value) if value == serde_json::json!("asr.final_update")
        ));
    }
}
